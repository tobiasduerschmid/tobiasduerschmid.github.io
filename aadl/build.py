#!/usr/bin/env python3
"""Build the Java 21 bytecode bridge; optional import verifies each pinned OSATE JAR."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "js/vendor/aadl/0.3.0"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify(path, expected):
    if not path.is_file() or digest(path) != expected:
        raise SystemExit(f"Missing or mismatched pinned artifact: {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jdk", type=Path, help="JDK home supporting --release 21")
    parser.add_argument("--distribution", type=Path, help="Extracted official osate-cli 0.3.0 distribution to import")
    parser.add_argument("--test", action="store_true")
    args = parser.parse_args()
    jdk = args.jdk or (Path(os.environ["JAVA_HOME"]) if os.environ.get("JAVA_HOME") else None)
    javac = str(jdk / "bin/javac") if jdk else shutil.which("javac")
    java = str(jdk / "bin/java") if jdk else shutil.which("java")
    if not javac or not java:
        raise SystemExit("Supply a JDK supporting --release 21 with --jdk.")
    lock = json.loads((ROOT / "aadl/dependencies.json").read_text())
    VENDOR.mkdir(parents=True, exist_ok=True)
    for artifact in lock["artifacts"]:
        target = VENDOR / artifact["name"]
        if args.distribution:
            source = args.distribution / "lib" / artifact["name"]
            verify(source, artifact["sha256"])
            shutil.copyfile(source, target)
        verify(target, artifact["sha256"])
    with tempfile.TemporaryDirectory(prefix="sebook-aadl-build-") as temporary:
        classes = Path(temporary) / "classes"
        classes.mkdir()
        sources = sorted((ROOT / "aadl/src").rglob("*.java"))
        subprocess.run([javac, "--release", "21", "-cp", str(VENDOR / "*"), "-d", str(classes), *map(str, sources)], check=True)
        bridge = VENDOR / "sebook-aadl-bridge.jar"
        entries = {path.relative_to(classes).as_posix(): path.read_bytes() for path in classes.rglob("*.class")}
        entries["META-INF/MANIFEST.MF"] = b"Manifest-Version: 1.0\nMain-Class: sebook.aadl.Bridge\n\n"
        with zipfile.ZipFile(bridge, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
            for name, data in sorted(entries.items()):
                entry = zipfile.ZipInfo(name, (2026, 11, 1, 0, 0, 0))
                entry.compress_type = zipfile.ZIP_DEFLATED
                entry.external_attr = 0o644 << 16
                archive.writestr(entry, data)
    artifacts = [*lock["artifacts"], {"name": bridge.name, "sha256": digest(bridge), "bytes": bridge.stat().st_size}]
    (VENDOR / "SHA256SUMS").write_text("".join(f"{item['sha256']}  {item['name']}\n" for item in artifacts))
    manifest = [{"name": item["name"], "path": "../vendor/aadl/0.3.0/" + item["name"], "sha256": item["sha256"], "bytes": item["bytes"]} for item in artifacts]
    (ROOT / "js/aadl").mkdir(exist_ok=True)
    (ROOT / "js/aadl/runtime-manifest.mjs").write_text("// Generated by aadl/build.py from the pinned dependency lock.\nexport const ARTIFACTS = Object.freeze(" + json.dumps(manifest, indent=2) + ");\n")
    print(f"Built {bridge.relative_to(ROOT)}; {len(artifacts)} artifacts, {sum(item['bytes'] for item in artifacts):,} bytes")
    if args.test:
        subprocess.run(["python3", str(ROOT / "aadl/test_bridge.py"), "--java", java], check=True)
        if jdk:
            subprocess.run(["python3", str(ROOT / "aadl/test_type_annotations.py"), "--jdk", str(jdk)], check=True)


if __name__ == "__main__":
    main()
