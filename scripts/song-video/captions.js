/**
 * WebVTT captions for an SE Book song video, built from the storyboard's
 * lyric lines so the captions, the on-page transcript, and the video share
 * one script (WCAG 1.2.2):
 *
 *   - sung lines are framed with music notes (♪ … ♪), spoken lines are not;
 *   - a call-and-response line becomes two cues, the question and then the
 *     crowd's answer from `answer_at`; a question the recording never
 *     answers (no `answer_at`) is one cue, like any sung line;
 *   - stretches of at least MUSIC_GAP seconds without words get a "[music]"
 *     cue, so captions-on viewers know the soundtrack is still playing.
 */
'use strict';

const MUSIC_GAP = 1.5;
const LINGER = 0.5; // seconds a cue stays up after its last word

function timestamp(seconds) {
  const totalMs = Math.round(seconds * 1000);
  const ms = String(totalMs % 1000).padStart(3, '0');
  const s = String(Math.floor(totalMs / 1000) % 60).padStart(2, '0');
  const m = String(Math.floor(totalMs / 60000) % 60).padStart(2, '0');
  const h = String(Math.floor(totalMs / 3600000)).padStart(2, '0');
  return `${h}:${m}:${s}.${ms}`;
}

/** Every timed caption of the song, in order, without overlaps. */
function lyricCues(storyboard) {
  const sung = (section, text) => (section.delivery === 'spoken' ? text : `♪ ${text} ♪`);
  const cues = [];
  for (const section of storyboard.sections) {
    for (const line of section.lines) {
      if (section.delivery === 'call' && Number.isFinite(line.answer_at)) {
        cues.push({ start: line.start, end: line.answer_at, text: sung(section, line.text) });
        cues.push({ start: line.answer_at, end: line.end, text: sung(section, `(crowd) ${line.answer}`) });
      } else {
        cues.push({ start: line.start, end: line.end, text: sung(section, line.text) });
      }
    }
  }
  cues.forEach((cue, i) => {
    const next = i + 1 < cues.length ? cues[i + 1].start : storyboard.duration;
    cue.end = Math.min(next, Math.max(cue.end + LINGER, cue.start + 1));
  });
  return cues;
}

function withMusicCues(cues, duration) {
  const out = [];
  let cursor = 0;
  for (const cue of [...cues, { start: duration, end: duration }]) {
    if (cue.start - cursor >= MUSIC_GAP) out.push({ start: cursor, end: cue.start, text: '[music]' });
    if (cue.end > cue.start) out.push(cue);
    cursor = Math.max(cursor, cue.end);
  }
  return out;
}

const GENERATED_NOTE = 'Generated by scripts/song-video/render.js from the song storyboard in _data/songs/; edit that file, not this one.';

function toVtt(cues) {
  const blocks = cues.map((cue, i) => `${i + 1}\n${timestamp(cue.start)} --> ${timestamp(cue.end)}\n${cue.text}`);
  return `WEBVTT\n\nNOTE\n${GENERATED_NOTE}\n\n${blocks.join('\n\n')}\n`;
}

function songCaptions(storyboard) {
  return toVtt(withMusicCues(lyricCues(storyboard), storyboard.duration));
}

/**
 * The narrator's description split into sentences, spread over the time the
 * voice speaks in proportion to their length, each marked "(narrator)".
 */
function narrationCues(hold) {
  // Split only where punctuation meets a space, so "app.py" stays whole.
  const sentences = hold.narration.split(/(?<=[.!?])\s+/);
  const total = sentences.reduce((sum, s) => sum + s.length, 0);
  let at = hold.speechStart;
  return sentences.map((sentence) => {
    const start = at;
    at += (hold.speechEnd - hold.speechStart) * (sentence.length / total);
    return { start, end: at, text: `(narrator) ${sentence}` };
  });
}

/**
 * Captions for the audio-described cut (see described-cut.js): the
 * narration during each hold, and every lyric cue moved later by the holds
 * that come before it, never running into the next hold.
 */
function describedCaptions(storyboard, plan) {
  const { holds } = plan;
  const lyrics = lyricCues(storyboard).map((cue) => {
    let index = 0;
    while (index + 1 < holds.length && holds[index + 1].songTime <= cue.start) index++;
    const hold = holds[index];
    const shift = hold.outputEnd - hold.songTime;
    const limit = index + 1 < holds.length ? holds[index + 1].outputStart : plan.duration;
    return { start: cue.start + shift, end: Math.min(cue.end + shift, limit), text: cue.text };
  });
  const cues = [...holds.flatMap(narrationCues), ...lyrics].sort((a, b) => a.start - b.start);
  return toVtt(withMusicCues(cues, plan.duration));
}

module.exports = { songCaptions, describedCaptions, lyricCues };
