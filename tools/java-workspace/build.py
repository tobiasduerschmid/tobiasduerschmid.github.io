#!/usr/bin/env python3
"""Build the Java 8 tutorial bridge and pin its served classpath. Requires a Java 8 JDK."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
VENDOR = ROOT / "js/vendor/java"
JARS = {
    VENDOR / "ecj-3.26.0.jar": "ac0ba5876eaf7ebb47749a0d1be179c51f194b9dd0b875d1c09e1b530f5a2db5",
    ROOT / "js/vendor/aadl/0.3.0/com.google.gson_2.13.2.jar": "dd0ce1b55a3ed2080cb70f9c655850cda86c206862310009dcb5e5c95265a5e0",
    VENDOR / "asm-9.7.1.jar": "8cadd43ac5eb6d09de05faecca38b917a040bb9139c7edeb4cc81c740b713281",
    VENDOR / "asm-tree-9.7.1.jar": "9929881f59eb6b840e86d54570c77b59ce721d104e6dfd7a40978991c2d3b41f",
}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--javac", default="javac")
    args = parser.parse_args()
    for path, expected in JARS.items():
        if digest(path) != expected:
            raise SystemExit(f"Incorrect pinned dependency: {path}")
    archive = VENDOR / "sebook-java-bridge.jar"
    with tempfile.TemporaryDirectory() as output:
        subprocess.run([args.javac, "-encoding", "UTF-8", "-source", "8", "-target", "8",
                        "-cp", ":".join(map(str,JARS)), "-d", output,
                        *map(str, sorted((HERE / "sebook").rglob("*.java")))], check=True)
        with zipfile.ZipFile(archive, "w") as jar:
            for file in sorted(Path(output).rglob("*.class")):
                entry = zipfile.ZipInfo(file.relative_to(output).as_posix())
                jar.writestr(entry, file.read_bytes(), compress_type=zipfile.ZIP_DEFLATED)
    manifest = [{"name": path.name, "path": "../" + path.relative_to(ROOT / "js").as_posix(),
                 "sha256": digest(path)} for path in [*JARS,archive]]
    (ROOT / "js/java/runtime-manifest.mjs").write_text(
        "// Generated by tools/java-workspace/build.py.\nexport const ARTIFACTS = " + json.dumps(manifest, indent=2) + ";\n")


if __name__ == "__main__":
    main()
